<h3>Google Fonts</h3>
<p>
    Diese Seite bindet Schriftarten von Google (Google Fonts) ein, die von Servern der Google Ireland
    Limited, Gordon House, Barrow Street, Dublin 4, Irland, geladen werden. Beim Aufruf einer Seite lädt
    Ihr Browser die benötigten Schriften in den Browsercache; dabei nimmt Ihr Browser eine Verbindung zu
    den Servern von Google auf und übermittelt dabei Ihre IP-Adresse und die aufgerufene Seite. Eine
    Übertragung in die USA kann dabei nicht ausgeschlossen werden; Grundlage ist der
    EU-US Data Privacy Framework. Rechtsgrundlage ist Art. 6 Abs. 1 lit. f DSGVO (berechtigtes Interesse
    an einer einheitlichen Darstellung des Angebots). Weitere Informationen finden Sie unter
    <a href="https://policies.google.com/privacy" target="_blank" rel="noopener">policies.google.com/privacy</a>.
</p>
