<h3>OpenStreetMap</h3>
<p>
    Für die interaktive Kartenansicht laden wir Kartenkacheln von den Servern der OpenStreetMap Foundation,
    St John's Innovation Centre, Cowley Road, Cambridge, CB4 0WS, Vereinigtes Königreich. Dabei wird Ihre
    IP-Adresse an die OpenStreetMap Foundation übertragen; ohne diese Übertragung lässt sich die Karte
    nicht darstellen. Rechtsgrundlage ist Art. 6 Abs. 1 lit. f DSGVO (berechtigtes Interesse an einer
    verständlichen Kartendarstellung). Für das Vereinigte Königreich besteht ein Angemessenheitsbeschluss
    der Europäischen Kommission. Näheres entnehmen Sie der Datenschutzerklärung der OpenStreetMap
    Foundation unter
    <a href="https://osmfoundation.org/wiki/Privacy_Policy" target="_blank" rel="noopener">osmfoundation.org</a>.
</p>
