<h3>Umami (cookielose Reichweitenmessung)</h3>
<p>
    Wir nutzen Umami, eine cookielose Reichweitenmessung, die Seitenaufrufe ohne persönliche Profile zählt;
    IP-Adressen werden nicht gespeichert. Die Software läuft auf einem von uns betriebenen Server bei der
    Hetzner Online GmbH (Rechenzentrum in Deutschland); die Daten werden nicht an Dritte weitergegeben.
    Rechtsgrundlage ist Art. 6 Abs. 1 lit. f DSGVO (berechtigtes Interesse an der Auswertung der Nutzung).
    Eine Einwilligung ist nicht erforderlich, weil keine Informationen auf Ihrem Endgerät gespeichert oder
    ausgelesen werden.
</p>
