<h3>Adresssuche mit Vorschlägen (LocationIQ)</h3>
<p>
    Wenn Sie in die Adresssuche tippen, zeigen wir passende Adressvorschläge an. Dazu übermittelt unser
    Server den eingegebenen Suchtext an den Geodienst LocationIQ der Unwired Labs (India) Pvt. Ltd. Die
    Anfrage geht von unserem Server aus: Ihre IP-Adresse, Browserdaten oder Cookies erreichen den Anbieter
    dabei nicht. Übermittelt wird ausschließlich der Suchtext, also in der Regel Straße, Hausnummer,
    Postleitzahl und Ort eines Grundstücks. Um wiederholte Anfragen zu vermeiden, speichern wir Suchtext
    und Vorschläge ohne Bezug zu Ihrer Person bis zu 30 Tage auf unserem Server.
</p>
<p>
    Zu einer ausgewählten Adresse ermitteln wir aus Postleitzahl und Ort das zuständige Grundbuchamt über
    unser eigenes Behördenverzeichnis (amtfinder.de); dabei werden keine Daten an Dritte übertragen.
    Rechtsgrundlage ist Art. 6 Abs. 1 lit. b DSGVO (Anbahnung des Vertrags) sowie Art. 6 Abs. 1 lit. f
    DSGVO (berechtigtes Interesse an einer fehlerfreien Adresseingabe). Eine Übermittlung in ein Drittland
    kann nicht ausgeschlossen werden; sie betrifft keine Daten, die Sie unmittelbar identifizieren. Näheres
    entnehmen Sie der Datenschutzerklärung des Anbieters unter
    <a href="https://locationiq.com/privacy" target="_blank" rel="noopener">locationiq.com/privacy</a>.
</p>
